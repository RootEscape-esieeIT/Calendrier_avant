  function t(texte, vars) {
    let s = langue === 'en' && Object.prototype.hasOwnProperty.call(EN, texte) ? EN[texte] : texte;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? vars[k] : m));
    return s;
  }
  // Pluriel : en français, « 0 » et « 1 » sont au singulier ; en anglais, seul « 1 » l'est.
  const pluriel = (n) => (langue === 'en' ? n !== 1 : n >= 2);
  const locale = langue === 'en' ? 'en-US' : 'fr-FR';
  const nombre = (n) => Number(n).toLocaleString(locale);
  const dateTexte = (n) => (langue === 'en' ? `December ${n}` : `${n === 1 ? '1er' : n} décembre`);
  const dateCourte = (n) => (langue === 'en' ? `Dec ${n}` : `${n === 1 ? '1er' : n} déc.`);

  function changer(l) {
    const q = lirePrefs();
    q.langue = l;
    try { localStorage.setItem(CLE, JSON.stringify(q)); } catch (e) { /* tant pis */ }
    location.reload();
  }

  // Traduit les textes fixes de index.html (attribut data-t = texte français d'origine).
  function traduirePage() {
    if (langue === 'fr') return;
    document.title = t('PAGE_TITRE');
    document.querySelectorAll('[data-t]').forEach(el => { el.textContent = t(el.getAttribute('data-t') || el.textContent.trim()); });
    document.querySelectorAll('[data-t-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-t-html')); });
    ['title', 'aria-label'].forEach(attr => document.querySelectorAll(`[data-t-${attr}]`).forEach(el => el.setAttribute(attr, t(el.getAttribute(`data-t-${attr}`)))));
  }

  global.I18N = { langue, t, pluriel, locale, nombre, dateTexte, dateCourte, changer, traduirePage, EN };
